"""Shared leaderboard-entry construction for baselines and CI-certified submissions.

Both ``populate_baselines.py`` (literature references on HOLDOUT_SEED) and
``verifier_and_runner.py --mode=certify`` (challenge submissions on the blind seed)
emit entries through :func:`build_entry`, so every row in ``leaderboard.json`` has the
same per-scale schema and the page can render it. Entries carry ``source`` =
``"literature"`` or ``"challenge"``.
"""
from __future__ import annotations

import datetime as _dt
import os
import sys
from typing import Any

_HERE = os.path.dirname(os.path.abspath(__file__))
_ROOT = os.path.dirname(_HERE)
if _ROOT not in sys.path:
    sys.path.insert(0, _ROOT)

import numpy as np

from leaderboard.schema_and_api import validate_leaderboard_entry


def clean_scale_dict(
    m: dict[str, Any],
    scale_nmax: int,
    *,
    num_rounds_mean: float = 1.0,
    crlb95: float | None = None,
    extra: dict[str, Any] | None = None,
) -> dict[str, Any]:
    """Strip raw trial arrays and normalize a per-scale metric dict for JSON export."""
    q_mean = float(m["q_mean"])
    q_max = float(m["q_max"])
    q_std = float(m.get("q_std", 0.0))
    md_mean = float(m.get("max_depth_mean", scale_nmax))
    sd_mean = float(m.get("seq_depth_mean", md_mean))
    eps95 = float(m["eps95"])

    c68_ci = m.get("C68_ave_ci", (float(m["C68_ave"]), float(m["C68_ave"])))
    c95_ci = m.get("C95_ave_ci", (float(m["C95_ave"]), float(m["C95_ave"])))
    c99_ci = m.get("C99_ave_ci", (float(m["C99_ave"]), float(m["C99_ave"])))
    c68_mci = m.get("C68_max_ci", (float(m["C68_max"]), float(m["C68_max"])))
    c95_mci = m.get("C95_max_ci", (float(m["C95_max"]), float(m["C95_max"])))
    c99_mci = m.get("C99_max_ci", (float(m["C99_max"]), float(m["C99_max"])))
    q_spread_val = round(float(q_std / q_mean) if q_mean > 0 else 0.0, 5)
    c95_seq_val = round(float(m.get("C95_seq", eps95 * sd_mean)), 4)

    out: dict[str, Any] = {
        "scale_nmax": int(scale_nmax),
        "ntrials": int(m["ntrials"]),
        "q_mean": round(q_mean, 2),
        "q_ave": round(q_mean, 2),
        "q_max": round(q_max, 2),
        "q_std": round(q_std, 4),
        "query_spread": q_spread_val,
        "q_spread": q_spread_val,
        "max_depth_mean": round(md_mean, 2),
        "seq_depth_mean": round(sd_mean, 2),
        "num_rounds_mean": round(float(num_rounds_mean), 3),
        "eps50": float(f"{m['eps50']:.6e}"),
        "eps68": float(f"{m['eps68']:.6e}"),
        "eps95": float(f"{eps95:.6e}"),
        "eps99": float(f"{m['eps99']:.6e}"),
        "C50_ave": round(float(m["C50_ave"]), 4),
        "C68_ave": round(float(m["C68_ave"]), 4),
        "C68_max": round(float(m["C68_max"]), 4),
        "C68_ave_ci": [round(float(c68_ci[0]), 4), round(float(c68_ci[1]), 4)],
        "C68_ci": [round(float(c68_ci[0]), 4), round(float(c68_ci[1]), 4)],
        "C68_max_ci": [round(float(c68_mci[0]), 4), round(float(c68_mci[1]), 4)],
        "C95_ave": round(float(m["C95_ave"]), 4),
        "C95_max": round(float(m["C95_max"]), 4),
        "C95_ave_ci": [round(float(c95_ci[0]), 4), round(float(c95_ci[1]), 4)],
        "C95_ci": [round(float(c95_ci[0]), 4), round(float(c95_ci[1]), 4)],
        "C95_max_ci": [round(float(c95_mci[0]), 4), round(float(c95_mci[1]), 4)],
        "C99_ave": round(float(m["C99_ave"]), 4),
        "C99_max": round(float(m["C99_max"]), 4),
        "C99_ave_ci": [round(float(c99_ci[0]), 4), round(float(c99_ci[1]), 4)],
        "C99_ci": [round(float(c99_ci[0]), 4), round(float(c99_ci[1]), 4)],
        "C99_max_ci": [round(float(c99_mci[0]), 4), round(float(c99_mci[1]), 4)],
        "C95_seq": c95_seq_val,
        "C95_par": round(float(eps95 * md_mean), 4),
    }
    if crlb95 is not None:
        out["C95_crlb"] = round(float(crlb95), 4)
        out["ratio_crlb95"] = round(float(m["C95_ave"]) / float(crlb95), 4)
    if extra:
        out.update(extra)
    return out


def build_entry(
    *,
    algo_id: str,
    algorithm_name: str,
    category: str,
    track: str,
    badge: str,
    authors: list[str],
    github_handle: str,
    affiliation: str,
    paper_url: str | None,
    pr_number: int | str | None,
    description: str,
    scales_dict: dict[str, dict[str, Any]],
    deterministic_budget: bool,
    agent_origin: str,
    repro_cmd: str = "OPENBLAS_NUM_THREADS=1 .venv/bin/python leaderboard/populate_baselines.py",
    date_str: str = "2026-09-04",
    extra_summary: dict[str, Any] | None = None,
    source: str = "literature",
    status: str = "Literature Ref",
    is_baseline: bool = True,
) -> dict[str, Any]:
    """Assemble and validate a canonical leaderboard entry across the benchmark scales.

    ``source`` separates the two kinds of rows the page shows: ``"literature"`` for the
    reference methods regenerated by ``populate_baselines.py`` on HOLDOUT_SEED, and
    ``"challenge"`` for pull-request submissions certified by CI on the blind seed.
    """
    vals = list(scales_dict.values())

    def _mean(key: str) -> float:
        return round(float(np.mean([v[key] for v in vals if v.get(key) is not None])), 4)

    c68_ave = _mean("C68_ave")
    c68_max = _mean("C68_max")
    c95_ave = _mean("C95_ave")
    c95_max = _mean("C95_max")
    c99_ave = _mean("C99_ave")
    c99_max = _mean("C99_max")
    c95_seq = _mean("C95_seq")
    c95_par = _mean("C95_par")
    rounds_mean = _mean("num_rounds_mean")
    q_spread = round(float(np.mean([v["query_spread"] for v in vals])), 5)

    c68_ci_mean = [
        round(float(np.mean([v["C68_ave_ci"][0] for v in vals])), 4),
        round(float(np.mean([v["C68_ave_ci"][1] for v in vals])), 4),
    ]
    c95_ci_mean = [
        round(float(np.mean([v["C95_ave_ci"][0] for v in vals])), 4),
        round(float(np.mean([v["C95_ave_ci"][1] for v in vals])), 4),
    ]
    c99_ci_mean = [
        round(float(np.mean([v["C99_ave_ci"][0] for v in vals])), 4),
        round(float(np.mean([v["C99_ave_ci"][1] for v in vals])), 4),
    ]

    if abs(rounds_mean - 1.0) < 1e-3:
        rounds_label = "1 (Parallel)"
    elif abs(rounds_mean - 2.0) < 1e-3:
        rounds_label = "2 (Exact)"
    elif rounds_mean < 4.0:
        rounds_label = f"~{rounds_mean:.2f} Rnds"
    else:
        rounds_label = f"Adaptive (~{rounds_mean:.1f})"

    entry: dict[str, Any] = {
        "algo_id": algo_id,
        "algorithm_name": algorithm_name,
        "name": algorithm_name,
        "category": category,
        "badge": badge,
        "track": track,
        "track_category": track,
        "authors": authors,
        "github_handle": github_handle,
        "affiliation": affiliation,
        "paper_url": paper_url,
        "pr_number": pr_number,
        "description": description,
        "date": date_str,
        "source": source,
        "status": status,
        "repro_cmd": repro_cmd,
        "agent_origin": agent_origin,
        "is_baseline": bool(is_baseline),
        "verified": True,
        "deterministic_budget": bool(deterministic_budget),
        "rounds": rounds_label,
        "rounds_num": rounds_mean,
        "num_rounds_mean": rounds_mean,
        "query_spread": q_spread,
        "q_spread": q_spread,
        "C68_ave": c68_ave,
        "C68_max": c68_max,
        "C68_ave_ci": c68_ci_mean,
        "C95_ave": c95_ave,
        "C95_max": c95_max,
        "C95_ave_ci": c95_ci_mean,
        "C95_ci": c95_ci_mean,
        "C99_ave": c99_ave,
        "C99_max": c99_max,
        "C99_ave_ci": c99_ci_mean,
        "C99_ci": c99_ci_mean,
        "C95_seq": c95_seq,
        "C95_par": c95_par,
        "headline_C95_ave": c95_ave,
        "headline_C95_max": c95_max,
        "headline_C99_ave": c99_ave,
        "scales": scales_dict,
    }
    if extra_summary:
        entry.update(extra_summary)
    return validate_leaderboard_entry(entry)


def _coerce_pr_number(value: Any) -> int | None:
    if isinstance(value, bool):
        return None
    if isinstance(value, int):
        return value
    if isinstance(value, str) and value.strip().isdigit():
        return int(value.strip())
    return None


def entry_from_benchmark(
    bench: dict[str, Any],
    *,
    meta: dict[str, Any],
    algo_id: str,
    verified: bool = True,
    certified_by: str = "CI certifier (blind HMAC-derived seed)",
) -> dict[str, Any]:
    """Turn the output of ``benchmark_submission`` plus a submission's ``metadata.json``
    into a full challenge entry in the same schema as the literature baselines."""
    per_scale = bench["standard_prior"]["per_scale"]
    scales_dict: dict[str, dict[str, Any]] = {}
    for nmax in sorted(int(k) for k in per_scale):
        m = per_scale[nmax] if nmax in per_scale else per_scale[str(nmax)]
        scales_dict[str(nmax)] = clean_scale_dict(
            m,
            nmax,
            num_rounds_mean=float(m.get("rounds_mean", 1.0)),
            extra={"runtime_per_trial_ms": round(float(m.get("runtime_per_trial_ms", 0.0)), 3)},
        )
    deterministic = all(float(v.get("query_spread", 0.0)) < 1e-9 for v in scales_dict.values())
    wide = bench.get("wide_prior", {}).get("summary", {}) or {}
    name = meta.get("algorithm_name") or meta.get("name") or algo_id
    repro = (
        "python3 leaderboard/verifier_and_runner.py --mode=certify "
        f"--submission=leaderboard/submissions/{algo_id} --ntrials=20000"
    )
    extra: dict[str, Any] = {
        "submission_path": algo_id,
        "certified_by": certified_by,
        "ntrials": int(bench.get("ntrials", 0)),
        "blind_secret_active": bool(bench.get("blind_secret_active", False)),
    }
    if wide.get("C95_ave") is not None:
        extra["wide_prior_C95_ave"] = round(float(wide["C95_ave"]), 4)
    if wide.get("C99_ave") is not None:
        extra["wide_prior_C99_ave"] = round(float(wide["C99_ave"]), 4)
    entry = build_entry(
        algo_id=algo_id,
        algorithm_name=str(name),
        category="challenge",
        track=str(meta["track"]),
        badge="Challenge submission",
        authors=[str(a) for a in (meta.get("authors") or ["Unknown"])],
        github_handle=str(meta.get("github_handle") or "unitaryfoundation"),
        affiliation=str(meta.get("affiliation") or "Unspecified"),
        paper_url=meta.get("paper_url") or None,
        pr_number=_coerce_pr_number(meta.get("pr_number")),
        description=str(meta.get("description") or name),
        scales_dict=scales_dict,
        deterministic_budget=deterministic,
        agent_origin="Challenge submission",
        repro_cmd=repro,
        date_str=str(meta.get("date") or _dt.date.today().isoformat()),
        extra_summary=extra,
        source="challenge",
        status="Certified" if verified else "Unverified",
        is_baseline=False,
    )
    entry["verified"] = bool(verified)
    return entry
